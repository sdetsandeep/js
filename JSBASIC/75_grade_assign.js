// 75	75_grade_assign.js	Assign grade A/B/C/D/F to a student based on their marks.

let marks = 78;
console.log("Marks:", marks);
if (marks >= 90) {
    console.log("Grade: A");
} else if (marks >= 75) {
    console.log("Grade: B");
} else if (marks >= 60) {
    console.log("Grade: C");
} else if (marks >= 40) {
    console.log("Grade: D");
} else {
    console.log("Grade: F");
}
