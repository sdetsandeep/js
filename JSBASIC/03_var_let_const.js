//4	var_let_const.js	Declare variables using var, let, and const and observe their differences.
// Using var
var studentName = "Sandeep";
console.log("var:", studentName);

studentName = "Rahul"; // Reassignment allowed
console.log("var after reassignment:", studentName);


// Using let
let age = 25;
console.log("let:", age);

age = 26; // Reassignment allowed
console.log("let after reassignment:", age);
