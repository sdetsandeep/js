// 30	30_decrement.js	Decrement a variable using the -- operator (both pre and post).

let a = 10;
console.log("Original value:", a);
console.log("Post-decrement (a--):", a--);
console.log("After post-decrement:", a);
console.log("Pre-decrement (--a):", --a);
console.log("After pre-decrement:", a);
