// 31	31_plus_assign.java	Use += operator to add a value to an existing variable.
public class _31_plus_assign {
    public static void main(String[] args) {
        int num = 10;
        System.out.println("Original: " + num);
        num += 5;
        System.out.println("After num += 5: " + num);
    }
}
