// 52	52_between_10_100.java	Check if a number lies between 10 and 100 (inclusive).
public class _52_between_10_100 {
    public static void main(String[] args) {
        int num = 55;
        boolean result = num >= 10 && num <= 100;
        System.out.println("Number: " + num);
        System.out.println("Is between 10 and 100: " + result);
    }
}
