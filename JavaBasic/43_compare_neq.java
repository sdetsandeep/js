// 43	43_compare_neq.java	Compare two numbers using != operator and print the result.
public class _43_compare_neq {
    public static void main(String[] args) {
        int a = 10, b = 20;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a != b: " + (a != b));
        System.out.println("a != 10: " + (a != 10));
    }
}
