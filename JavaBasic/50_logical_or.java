// 50	50_logical_or.java	Use logical OR (||) to check if at least one condition is true.
public class _50_logical_or {
    public static void main(String[] args) {
        int a = 5, b = -3;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a > 0 || b > 0: " + (a > 0 || b > 0));
        System.out.println("a < 0 || b < 0: " + (a < 0 || b < 0));
    }
}
