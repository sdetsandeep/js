// 63	63_is_zero.java	Check whether a given number is exactly zero.
public class _63_is_zero {
    public static void main(String[] args) {
        int num = 0;
        System.out.println("Number: " + num);
        if (num == 0) System.out.println("The number is exactly zero.");
        else System.out.println("The number is not zero.");
    }
}
