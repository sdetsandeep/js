// 24	24_divide_two.java	Write a program to divide two numbers and print the result.

public class _24_divide_two {
    public static void main(String[] args) {
        double a = 25, b = 4;
        double result = a / b;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a / b = " + result);
    }
}
