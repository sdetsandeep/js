// 51	51_logical_not.java	Use logical NOT (!) to reverse the value of a boolean.
public class _51_logical_not {
    public static void main(String[] args) {
        boolean isRaining = true;
        boolean isSunny = false;
        System.out.println("isRaining: " + isRaining + " | !isRaining: " + !isRaining);
        System.out.println("isSunny: " + isSunny + " | !isSunny: " + !isSunny);
    }
}
