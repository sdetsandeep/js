// 108	108_even_numbers.java	Print all even numbers from 1 to 100 using a loop.
public class _108_even_numbers {
    public static void main(String[] args) {
        System.out.println("Even numbers 1 to 100:");
        for (int i = 2; i <= 100; i += 2) System.out.print(i + " ");
        System.out.println();
    }
}
