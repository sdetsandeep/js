// 47	47_greater_equal.java	Check whether a number is greater than or equal to another using >=.
public class _47_greater_equal {
    public static void main(String[] args) {
        int a = 10, b = 10;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a >= b: " + (a >= b));
        System.out.println("a >= 5: " + (a >= 5));
    }
}
