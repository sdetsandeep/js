// 60	60_ternary_larger.java	Use the ternary operator to find and print the larger of two numbers.
public class _60_ternary_larger {
    public static void main(String[] args) {
        int a = 18, b = 25;
        int larger = (a > b) ? a : b;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("Larger: " + larger);
    }
}
