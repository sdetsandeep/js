// 109	109_odd_numbers.java	Print all odd numbers from 1 to 100 using a loop.
public class _109_odd_numbers {
    public static void main(String[] args) {
        System.out.println("Odd numbers 1 to 100:");
        for (int i = 1; i <= 100; i += 2) System.out.print(i + " ");
        System.out.println();
    }
}
