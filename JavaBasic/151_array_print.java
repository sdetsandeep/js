// 151	151_array_print.java	Create an array and print all its elements using a loop.
public class _151_array_print {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40, 50};
        for (int i = 0; i < arr.length; i++) System.out.println("Index " + i + ": " + arr[i]);
    }
}
