// 48	48_less_equal.java	Check whether a number is less than or equal to another using <=.
public class _48_less_equal {
    public static void main(String[] args) {
        int a = 8, b = 10;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a <= b: " + (a <= b));
        System.out.println("b <= a: " + (b <= a));
    }
}
