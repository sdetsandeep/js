// 149	149_multiples_of_5.java	Print all multiples of 5 from 1 to 100.
public class _149_multiples_of_5 {
    public static void main(String[] args) {
        System.out.print("Multiples of 5: ");
        for (int i = 5; i <= 100; i += 5) System.out.print(i + " ");
        System.out.println();
    }
}
