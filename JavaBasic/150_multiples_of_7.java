// 150	150_multiples_of_7.java	Print all multiples of 7 from 1 to 100.
public class _150_multiples_of_7 {
    public static void main(String[] args) {
        System.out.print("Multiples of 7: ");
        for (int i = 7; i <= 100; i += 7) System.out.print(i + " ");
        System.out.println();
    }
}
