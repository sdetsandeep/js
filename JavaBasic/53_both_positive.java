// 53	53_both_positive.java	Check whether both of two given numbers are positive.
public class _53_both_positive {
    public static void main(String[] args) {
        int a = 7, b = 3;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("Both positive: " + (a > 0 && b > 0));
    }
}
