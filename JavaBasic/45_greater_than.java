// 45	45_greater_than.java	Check whether one number is greater than another using >.
public class _45_greater_than {
    public static void main(String[] args) {
        int a = 15, b = 10;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a > b: " + (a > b));
        System.out.println("b > a: " + (b > a));
    }
}
