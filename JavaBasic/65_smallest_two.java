// 65	65_smallest_two.java	Find and print the smallest of two numbers using if-else.
public class _65_smallest_two {
    public static void main(String[] args) {
        int a = 34, b = 56;
        System.out.println("a = " + a + ", b = " + b);
        if (a < b) System.out.println("Smallest: " + a);
        else System.out.println("Smallest: " + b);
    }
}
