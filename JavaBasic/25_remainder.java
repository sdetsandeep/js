// 25	25_remainder.java	Find the remainder when one number is divided by another using % operator.

public class _25_remainder {
    public static void main(String[] args) {
        int a = 17, b = 5;
        int remainder = a % b;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a % b = " + remainder);
    }
}
