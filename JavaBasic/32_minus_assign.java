// 32	32_minus_assign.java	Use -= operator to subtract a value from an existing variable.
public class _32_minus_assign {
    public static void main(String[] args) {
        int num = 20;
        System.out.println("Original: " + num);
        num -= 8;
        System.out.println("After num -= 8: " + num);
    }
}
