// 64	64_largest_two.java	Find and print the largest of two numbers using if-else.
public class _64_largest_two {
    public static void main(String[] args) {
        int a = 34, b = 56;
        System.out.println("a = " + a + ", b = " + b);
        if (a > b) System.out.println("Largest: " + a);
        else System.out.println("Largest: " + b);
    }
}
