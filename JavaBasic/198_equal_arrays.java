// 198	198_equal_arrays.java	Check if two arrays are equal (same elements in same order).
import java.util.Arrays;
public class _198_equal_arrays {
    public static void main(String[] args) {
        int[] arr1={1,2,3,4,5}, arr2={1,2,3,4,5};
        System.out.println("Are equal: " + Arrays.equals(arr1, arr2));
    }
}
