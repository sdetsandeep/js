// 22	22_subtract_two.java	Write a program to subtract one number from another.

public class _22_subtract_two {
    public static void main(String[] args) {
        int a = 50, b = 18;
        int result = a - b;
        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a - b = " + result);
    }
}
