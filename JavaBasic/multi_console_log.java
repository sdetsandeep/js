// 16	multi_console_log.java	Print multiple variables in a single console.log() statement.

public class multi_console_log {
    public static void main(String[] args) {
        String name = "Raj";
        int age = 25;
        double marks = 88.5;
        boolean passed = true;

        System.out.println("Name: " + name + " | Age: " + age + " | Marks: " + marks + " | Passed: " + passed);
    }
}
