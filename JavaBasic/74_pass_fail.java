// 74	74_pass_fail.java	Check whether a student has passed or failed based on marks >= 40.
public class _74_pass_fail {
    public static void main(String[] args) {
        int marks = 55;
        System.out.println("Marks: " + marks);
        if (marks >= 40) System.out.println("Result: PASS");
        else System.out.println("Result: FAIL");
    }
}
