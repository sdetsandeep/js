// 41	41_compare_eq.java	Compare two numbers using == (loose equality) and print true/false.
public class _41_compare_eq {
    public static void main(String[] args) {
        int a = 5, b = 5, c = 10;
        System.out.println("a = " + a + ", b = " + b + ", c = " + c);
        System.out.println("a == b: " + (a == b));
        System.out.println("a == c: " + (a == c));
    }
}
